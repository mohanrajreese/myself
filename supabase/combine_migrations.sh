#!/usr/bin/env bash
# Writes supabase/combined_migrations.sql: every migration in order, in one
# file, for pasting into the Supabase SQL editor. Generated; never edit it by
# hand. `supabase db push` applies supabase/migrations/ and ignores this file.
# CI fails when the committed file does not match this script's output.
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
{
  echo "-- GENERATED by supabase/combine_migrations.sh from supabase/migrations/. Do not edit."
  echo "-- Apply with 'supabase db push' (preferred) or paste into the SQL editor once, on an empty project."
  echo
  for f in "$here"/migrations/*.sql; do
    echo "-- ===== $(basename "$f")"
    cat "$f"
    echo
  done
} > "$here/combined_migrations.sql"
